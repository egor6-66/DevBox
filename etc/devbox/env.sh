# Окружение скоупа для НЕинтерактивного bash: задачи редактора (`/bin/bash -c …`), скрипты, команды
# агентов. bash читает этот файл сам — его имя стоит в BASH_ENV (Dockerfile).
#
# Две части, и обе выгружаются один раз, сразу:
#  · переменные из `[env]` в `mise.toml` (например PGDATA). Шимы в PATH их не дают: шим передаёт
#    `[env]` только запущенному через него инструменту, самому bash — нет. Ставить инструменты
#    отсюда нельзя: файл читает каждый bash, а установка — долгая и шумная, её дело `devbox sync`;
#  · секреты fnox. Активация fnox из `/etc/bash.bashrc` сюда не годится: она лишь вешает хук на
#    PROMPT_COMMAND, а приглашения у неинтерактивного шелла нет — хук не срабатывает ни разу.
# Вывод обоих молчит: он попадал бы в вывод каждой задачи и каждого скрипта.
command -v mise >/dev/null 2>&1 && eval "$(MISE_AUTO_INSTALL=false mise env -s bash 2>/dev/null)"
command -v fnox >/dev/null 2>&1 && eval "$(fnox hook-env -s bash 2>/dev/null)"
