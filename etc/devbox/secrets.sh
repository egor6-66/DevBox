# Секреты скоупа для НЕинтерактивного bash: задачи редактора (`/bin/bash -c …`), скрипты, команды
# агентов. bash читает этот файл сам — его имя стоит в BASH_ENV (Dockerfile).
#
# Активация fnox из `/etc/bash.bashrc` сюда не годится: она лишь вешает хук на PROMPT_COMMAND, а
# приглашения у неинтерактивного шелла нет — хук не срабатывает ни разу. Поэтому здесь секреты
# выгружаются один раз, сразу. Сообщение fnox о выгруженном молчит: оно попадало бы в вывод
# каждой задачи и каждого скрипта.
command -v fnox >/dev/null 2>&1 && eval "$(fnox hook-env -s bash 2>/dev/null)"
